import { FONTS, FOOTERS, HEADING_STYLES, SECTION_VARIANTS } from '../model/variants';
import { TEMPLATES } from '../model/templates';

// Text written into every library: a short guide inside library.json, a full
// AGENTS.md for AI agents and a README.md for people. Lists of valid values are
// generated from the app's own tables so they never go out of date.

export const APP_URL = 'https://dawsonhorvath.com/resume-generator/';

/** Kept in library.json so an agent that only reads that file knows where to look. */
export const AGENT_GUIDE = [
  'This folder is a resume library made with Resume Builder (' + APP_URL + ').',
  'Each resume is one file: resumes/**/<name>.resume.json. Folders under resumes/ group them.',
  'Read AGENTS.md before editing: it explains the format, the rules that keep a file valid, and how to make a tailored copy.',
  'resume.schema.json is a JSON Schema for a .resume.json file; validate edited files against it.',
  'Never invent experience, dates, numbers or credentials. Rephrase, reorder, trim and select; ask the person for anything new.',
];

const list = (items: string[]) => items.map((i) => `\`${i}\``).join(', ');

export function agentsMarkdown(): string {
  const variants = Object.entries(SECTION_VARIANTS)
    .map(([type, opts]) => `| \`${type}\` | ${list(opts.map((o) => o.id))} |`)
    .join('\n');
  return `# Working on this resume library (for AI agents)

This folder holds resumes made with Resume Builder (${APP_URL}).
People open the folder in the builder to see and edit them, and often keep it in git.
Your job is usually to make or update a version of a resume tailored to a job.

## Files

| Path | What it is |
|---|---|
| \`library.json\` | Library name, the default resume (\`defaultResume\`, a path) and a short guide. Change only \`name\` or \`defaultResume\`. |
| \`resumes/**/<name>.resume.json\` | One resume per file. Subfolders of \`resumes/\` group them (e.g. \`resumes/robotics/\`). |
| \`resume.schema.json\` | JSON Schema for one \`.resume.json\` file. |
| \`AGENTS.md\`, \`README.md\` | This guide, and the guide for people. Regenerated by the builder; don't edit. |

The builder finds every \`*.resume.json\` under \`resumes/\` on its own; there is no list to update.
File names are lowercase-with-dashes and end in \`.resume.json\`.

## Making a tailored copy

1. Copy the source file (usually the default resume) to a new path, e.g.
   \`resumes/applications/acme-robotics.resume.json\`.
2. In the copy set:
   - \`id\`: a new unique string, e.g. \`resume-acme-robotics\` (no other resume may use it);
   - \`title\`: a name the person will recognise, e.g. "Acme – Robotics Engineer";
   - \`meta.basedOn\`: the \`id\` of the source resume;
   - \`meta.target\`: the job or kind of job, e.g. "Robotics Engineer at Acme";
   - \`meta.notes\`: what you changed and why, in a sentence or two;
   - \`updatedAt\`: the current time as an ISO 8601 string.
3. Tailor the content: rewrite the summary for the role, reorder bullets so the
   most relevant come first, drop bullets or sections that don't help, and put
   the most relevant skills first. Keep the person's voice: plain, specific, no
   buzzwords.
4. Never add experience, employers, dates, numbers, skills or credentials the
   person doesn't have. If the job needs something that isn't there, say so to
   the person instead of writing it.
5. Keep the same number of pages unless asked. The builder shows a red outline
   on a page whose content no longer fits; tell the person to open the resume and
   use Layout → "Move it to the next page" if your edit made a page overflow.

## The format

A \`.resume.json\` file is one object:

\`\`\`
schema: "resume-generator"     always this value
version: 2                     always 2
id, title, updatedAt
meta: { basedOn, target, notes }
profile: { name, headline, email, phone, location, website, linkedin, github }
sections: Section[]            the content
pages: Page[]                  where each section appears
theme: { ... }                 fonts, colours, spacing
\`\`\`

### Sections (content)

Every section has \`id\` (unique in the file), \`type\`, \`title\`, \`variant\` (its style)
and \`showTitle\`. By type:

| type | extra fields |
|---|---|
| \`header\` | none: shows \`profile.name\` and \`profile.headline\` |
| \`contact\` | none: shows the contact fields of \`profile\` |
| \`text\` | \`body\`: a paragraph (blank lines separate paragraphs) |
| \`experience\`, \`education\` | \`items\`: entries \`{ id, title, subtitle, location, dates, note, description, bullets[], tags[], url }\` |
| \`skills\` | \`groups\`: \`{ id, name, skills[] }\` |
| \`list\` | \`items\`: strings |
| \`references\` | \`items\`: \`{ id, name, role, organization, email, phone, note }\`, and \`emptyText\` |
| \`spacer\` | \`height\` in cm |

Projects are usually an \`experience\` section titled "Projects".
For an experience entry, \`title\` is the role (or project name) and \`subtitle\` the
employer (or kind of project).

Valid \`variant\` values:

| type | variants |
|---|---|
${variants}

### Pages (layout)

\`pages\` is a list of A4 pages. Each page has \`id\`, \`footer\` and \`rows\`.
A row has \`id\`, \`columns\` (one or two lists of placements), \`split\` (width of the
left column in percent, 15–85) and \`shade\` (\`none\`, \`left\` or \`right\`: which
column gets the sidebar background; only for two columns).

A placement \`{ id, sectionId, from?, to? }\` puts a section in a column.
\`from\`/\`to\` show only items \`from\`..\`to - 1\` (0-based), which is how a long section
is split across pages: e.g. \`{ "sectionId": "exp", "to": 2 }\` on page 1 and
\`{ "sectionId": "exp", "from": 2 }\` on page 2.

Rules:
- Every \`sectionId\` must be the \`id\` of a section in the same file.
- A section that isn't placed anywhere isn't shown (that's allowed, e.g. to keep it for later).
- If you remove items from a split section, adjust \`from\`/\`to\` so the pieces still
  cover the items once each, in order.
- Placement, row and page ids must be unique in the file.

### Theme

\`template\` (${list(TEMPLATES.map((t) => t.id))}), \`font\` and \`headingFont\`
(${list(FONTS.map((f) => f.id))}), \`fontSize\` (points, 6–16), \`lineHeight\` (1–2.2),
\`spacing\` (0.4–2.5), \`headingStyle\` (${list(HEADING_STYLES.map((h) => h.id))}),
colours \`accent\`, \`text\`, \`muted\`, \`shade\`, \`shadeText\`, \`shadeAccent\` (\`#rrggbb\`),
\`margin\` and \`columnGap\` (cm, 0–5).
Page \`footer\`: ${list(FOOTERS.map((f) => f.id))}.

Out-of-range or unknown values are replaced with defaults when the file is opened,
so a mistake there won't break the file, but it may not look as intended.

## Checking your work

- The file must be valid JSON and match \`resume.schema.json\`.
- Re-read every changed bullet against the source resume: same facts, no new claims.
- Tell the person which file you created or changed, what you changed, and anything
  you left out because it wasn't supported by their resume.
`;
}

export function readmeMarkdown(name: string): string {
  return `# ${name}

Resumes made with [Resume Builder](${APP_URL}). Each resume is one file under
\`resumes/\`; folders group them (for example one folder per kind of job).

## Editing

Open ${APP_URL} in Chrome or Edge, then **File → Open resume folder…** and choose
this folder. The builder saves your edits straight into these files, and picks up
changes made here by other programs (an AI agent, a text editor, \`git pull\`)
when you switch back to it.

In other browsers, use the library file instead: **File → Open file…**, and
**File → Download library** to save it again.

To tailor a resume for a job: open the **Resumes** tab, choose **Make a copy** on
the resume to start from, and name it for the job. The copy remembers which resume
it came from.

## Using an AI agent

Point the agent at this folder and ask, for example: "Make a copy of my master
resume tailored to this job posting: …". \`AGENTS.md\` tells it how the files work
and what it must not change. Then switch back to the builder to see the result.

## Keeping versions with git

Keep this folder in a **private** repository; it holds your contact details.
The builder never connects to GitHub or any server; you commit and push with
your own git tools.

First time:

\`\`\`sh
cd path/to/this/folder
git init
git add .
git commit -m "My resumes"
# then create an empty private repository on GitHub and run the two commands it shows,
# e.g. git remote add origin … and git push -u origin main
\`\`\`

Day to day:

\`\`\`sh
git add . && git commit -m "Acme: tailored summary and skills"   # after a round of edits
git push
git tag sent/2026-03-acme                                         # mark exactly what you sent (year-month-company)
git push --tags
git diff master -- resumes/                                       # what changed since a branch or tag
git log -p -- resumes/applications/acme.resume.json               # history of one resume
\`\`\`

Tips:
- One file per job application makes it easy to see what was sent where.
- Tag each version you send (\`sent/<date>-<company>\`) so you can always reopen it.
- After switching branches or pulling, the builder updates on its own.
`;
}
